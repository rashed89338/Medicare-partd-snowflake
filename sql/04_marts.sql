-- Star schema: DIM_DRUG, FCT_DRUG_YEAR, FCT_MANUFACTURER_YEAR.
USE ROLE PARTD_ANALYST;
USE WAREHOUSE PARTD_WH;
USE SCHEMA MEDICARE_PARTD.MARTS;

CREATE OR REPLACE TABLE MARTS.DIM_DRUG AS
SELECT
    ROW_NUMBER() OVER (ORDER BY BRAND_NAME, GENERIC_NAME) AS DRUG_ID,
    BRAND_NAME,
    GENERIC_NAME,
    MAX(TOT_MFTR) AS MANUFACTURER_COUNT,
    -- Simple first-word comparison is a proxy, NOT an FDA product classification.
    CASE WHEN LOWER(SPLIT_PART(REPLACE(REPLACE(REPLACE(BRAND_NAME, '*', ''), '-', ' '), '/', ' '), ' ', 1))
            = LOWER(SPLIT_PART(REPLACE(REPLACE(GENERIC_NAME, '-', ' '), '/', ' '), ' ', 1))
         THEN 'Generic' ELSE 'Brand' END AS BRAND_OR_GENERIC,
    CASE
        WHEN LOWER(GENERIC_NAME) LIKE '%semaglutide%'
          OR LOWER(GENERIC_NAME) LIKE '%tirzepatide%'
          OR LOWER(GENERIC_NAME) LIKE '%dulaglutide%'
          OR LOWER(GENERIC_NAME) LIKE '%liraglutide%'
          OR LOWER(GENERIC_NAME) LIKE '%exenatide%'
          OR LOWER(GENERIC_NAME) LIKE '%lixisenatide%'
            THEN 'GLP-1 / GIP'
        WHEN LOWER(GENERIC_NAME) LIKE '%gliflozin%' THEN 'SGLT2 inhibitor'
        WHEN LOWER(GENERIC_NAME) LIKE '%gliptin%' THEN 'DPP-4 inhibitor'
        WHEN LOWER(GENERIC_NAME) LIKE '%insulin%' THEN 'Insulin'
        WHEN LOWER(GENERIC_NAME) LIKE 'apixaban%'
          OR LOWER(GENERIC_NAME) LIKE 'rivaroxaban%'
          OR LOWER(GENERIC_NAME) LIKE 'dabigatran%'
          OR LOWER(GENERIC_NAME) LIKE 'edoxaban%'
            THEN 'Anticoagulant (DOAC)'
        ELSE 'Other'
    END AS DRUG_CLASS
FROM STAGING.STG_DRUG_MFR_YEAR
WHERE MANUFACTURER = 'Overall'
GROUP BY BRAND_NAME, GENERIC_NAME;

CREATE OR REPLACE TABLE MARTS.FCT_DRUG_YEAR AS
SELECT d.DRUG_ID, s.YEAR,
       s.TOTAL_SPENDING, s.DOSAGE_UNITS, s.CLAIMS, s.BENEFICIARIES,
       s.SPEND_PER_UNIT, s.OUTLIER_FLAG
FROM STAGING.STG_DRUG_MFR_YEAR s
JOIN MARTS.DIM_DRUG d
  ON d.BRAND_NAME = s.BRAND_NAME AND d.GENERIC_NAME = s.GENERIC_NAME
WHERE s.MANUFACTURER = 'Overall';

CREATE OR REPLACE TABLE MARTS.FCT_MANUFACTURER_YEAR AS
SELECT MANUFACTURER, YEAR,
       SUM(TOTAL_SPENDING) AS TOTAL_SPENDING,
       SUM(CLAIMS) AS CLAIMS,
       COUNT(*) AS PRODUCTS
FROM STAGING.STG_DRUG_MFR_YEAR
WHERE MANUFACTURER <> 'Overall'
GROUP BY MANUFACTURER, YEAR;

CREATE OR REPLACE VIEW MARTS.V_DRUG_YEAR AS
SELECT d.BRAND_NAME, d.GENERIC_NAME, d.BRAND_OR_GENERIC, d.DRUG_CLASS, f.*
FROM MARTS.FCT_DRUG_YEAR f
JOIN MARTS.DIM_DRUG d USING (DRUG_ID);

-- Data quality checks: expected zero.
SELECT COUNT(*) AS DUP_DRUG_YEARS
FROM (SELECT DRUG_ID, YEAR
      FROM MARTS.FCT_DRUG_YEAR
      GROUP BY DRUG_ID, YEAR HAVING COUNT(*) > 1);
SELECT COUNT(*) AS NEGATIVE_SPEND
FROM MARTS.FCT_DRUG_YEAR WHERE TOTAL_SPENDING < 0;
