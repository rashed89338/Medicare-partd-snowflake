-- 01_setup.sql
-- Medicare Part D Drug Spending (CMS, 2020-2024) on Snowflake
-- Safe to rerun: does not replace an existing stage or file format.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS PARTD_ANALYST;
-- Keep original case, including lowercase usernames.
SET MY_USER = '"' || REPLACE(CURRENT_USER(), '"', '""') || '"';
GRANT ROLE PARTD_ANALYST TO USER IDENTIFIER($MY_USER);

CREATE WAREHOUSE IF NOT EXISTS PARTD_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
GRANT USAGE, OPERATE ON WAREHOUSE PARTD_WH TO ROLE PARTD_ANALYST;

CREATE RESOURCE MONITOR IF NOT EXISTS PARTD_MONITOR
  WITH CREDIT_QUOTA = 20 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE PARTD_WH SET RESOURCE_MONITOR = PARTD_MONITOR;

CREATE DATABASE IF NOT EXISTS MEDICARE_PARTD;
GRANT OWNERSHIP ON DATABASE MEDICARE_PARTD TO ROLE PARTD_ANALYST COPY CURRENT GRANTS;

USE ROLE PARTD_ANALYST;
USE WAREHOUSE PARTD_WH;
USE DATABASE MEDICARE_PARTD;

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS STAGING;
CREATE SCHEMA IF NOT EXISTS MARTS;

CREATE FILE FORMAT IF NOT EXISTS RAW.CSV_FMT
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE
  NULL_IF = ('', 'NULL');

CREATE STAGE IF NOT EXISTS RAW.CMS_STAGE
  FILE_FORMAT = RAW.CSV_FMT
  COMMENT = 'CMS Medicare Part D Spending by Drug, data.cms.gov dataset 7e0b4365-fd63-4a29-8f5e-e0ac9f66a81b';
