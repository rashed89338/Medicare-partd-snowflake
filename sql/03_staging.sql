-- 03_staging.sql
-- Wide to long: drug x manufacturer x year, with typed measures.
USE ROLE PARTD_ANALYST;
USE WAREHOUSE PARTD_WH;
USE SCHEMA MEDICARE_PARTD.STAGING;

CREATE OR REPLACE TABLE STAGING.STG_DRUG_MFR_YEAR AS
WITH UNPIVOTED AS (
    SELECT BRND_NAME, GNRC_NAME, MFTR_NAME,
           TRY_CAST(TOT_MFTR AS INTEGER) AS TOT_MFTR,
           2020 AS YEAR,
           TRY_CAST(TOT_SPNDNG_2020 AS DOUBLE) AS TOTAL_SPENDING,
           TRY_CAST(TOT_DSG_UNTS_2020 AS DOUBLE) AS DOSAGE_UNITS,
           TRY_CAST(TOT_CLMS_2020 AS DOUBLE) AS CLAIMS,
           TRY_CAST(TOT_BENES_2020 AS DOUBLE) AS BENEFICIARIES,
           TRY_CAST(AVG_SPND_PER_DSG_UNT_WGHTD_2020 AS DOUBLE) AS SPEND_PER_UNIT,
           TRY_CAST(OUTLIER_FLAG_2020 AS INTEGER) AS OUTLIER_FLAG
    FROM RAW.SPENDING_BY_DRUG
    UNION ALL
    SELECT BRND_NAME, GNRC_NAME, MFTR_NAME,
           TRY_CAST(TOT_MFTR AS INTEGER) AS TOT_MFTR,
           2021 AS YEAR,
           TRY_CAST(TOT_SPNDNG_2021 AS DOUBLE) AS TOTAL_SPENDING,
           TRY_CAST(TOT_DSG_UNTS_2021 AS DOUBLE) AS DOSAGE_UNITS,
           TRY_CAST(TOT_CLMS_2021 AS DOUBLE) AS CLAIMS,
           TRY_CAST(TOT_BENES_2021 AS DOUBLE) AS BENEFICIARIES,
           TRY_CAST(AVG_SPND_PER_DSG_UNT_WGHTD_2021 AS DOUBLE) AS SPEND_PER_UNIT,
           TRY_CAST(OUTLIER_FLAG_2021 AS INTEGER) AS OUTLIER_FLAG
    FROM RAW.SPENDING_BY_DRUG
    UNION ALL
    SELECT BRND_NAME, GNRC_NAME, MFTR_NAME,
           TRY_CAST(TOT_MFTR AS INTEGER) AS TOT_MFTR,
           2022 AS YEAR,
           TRY_CAST(TOT_SPNDNG_2022 AS DOUBLE) AS TOTAL_SPENDING,
           TRY_CAST(TOT_DSG_UNTS_2022 AS DOUBLE) AS DOSAGE_UNITS,
           TRY_CAST(TOT_CLMS_2022 AS DOUBLE) AS CLAIMS,
           TRY_CAST(TOT_BENES_2022 AS DOUBLE) AS BENEFICIARIES,
           TRY_CAST(AVG_SPND_PER_DSG_UNT_WGHTD_2022 AS DOUBLE) AS SPEND_PER_UNIT,
           TRY_CAST(OUTLIER_FLAG_2022 AS INTEGER) AS OUTLIER_FLAG
    FROM RAW.SPENDING_BY_DRUG
    UNION ALL
    SELECT BRND_NAME, GNRC_NAME, MFTR_NAME,
           TRY_CAST(TOT_MFTR AS INTEGER) AS TOT_MFTR,
           2023 AS YEAR,
           TRY_CAST(TOT_SPNDNG_2023 AS DOUBLE) AS TOTAL_SPENDING,
           TRY_CAST(TOT_DSG_UNTS_2023 AS DOUBLE) AS DOSAGE_UNITS,
           TRY_CAST(TOT_CLMS_2023 AS DOUBLE) AS CLAIMS,
           TRY_CAST(TOT_BENES_2023 AS DOUBLE) AS BENEFICIARIES,
           TRY_CAST(AVG_SPND_PER_DSG_UNT_WGHTD_2023 AS DOUBLE) AS SPEND_PER_UNIT,
           TRY_CAST(OUTLIER_FLAG_2023 AS INTEGER) AS OUTLIER_FLAG
    FROM RAW.SPENDING_BY_DRUG
    UNION ALL
    SELECT BRND_NAME, GNRC_NAME, MFTR_NAME,
           TRY_CAST(TOT_MFTR AS INTEGER) AS TOT_MFTR,
           2024 AS YEAR,
           TRY_CAST(TOT_SPNDNG_2024 AS DOUBLE) AS TOTAL_SPENDING,
           TRY_CAST(TOT_DSG_UNTS_2024 AS DOUBLE) AS DOSAGE_UNITS,
           TRY_CAST(TOT_CLMS_2024 AS DOUBLE) AS CLAIMS,
           TRY_CAST(TOT_BENES_2024 AS DOUBLE) AS BENEFICIARIES,
           TRY_CAST(AVG_SPND_PER_DSG_UNT_WGHTD_2024 AS DOUBLE) AS SPEND_PER_UNIT,
           TRY_CAST(OUTLIER_FLAG_2024 AS INTEGER) AS OUTLIER_FLAG
    FROM RAW.SPENDING_BY_DRUG
)
SELECT
    TRIM(BRND_NAME) AS BRAND_NAME,
    TRIM(GNRC_NAME) AS GENERIC_NAME,
    TRIM(MFTR_NAME) AS MANUFACTURER,
    TOT_MFTR,
    YEAR,
    TOTAL_SPENDING,
    DOSAGE_UNITS,
    CLAIMS,
    BENEFICIARIES,
    SPEND_PER_UNIT,
    OUTLIER_FLAG
FROM UNPIVOTED
WHERE TOTAL_SPENDING IS NOT NULL;
