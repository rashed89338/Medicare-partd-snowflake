-- 05_analysis.sql
-- Nine Medicare Part D analytical queries. Source: MARTS schema.
USE ROLE PARTD_ANALYST;
USE WAREHOUSE PARTD_WH;
USE SCHEMA MEDICARE_PARTD.MARTS;

-- @a1_yearly_totals
-- How fast is total drug spending growing?
WITH yearly AS (
    SELECT YEAR, SUM(TOTAL_SPENDING) AS SPENDING,
           SUM(CLAIMS) AS CLAIMS, COUNT(*) AS DRUGS_REPORTED
    FROM MARTS.FCT_DRUG_YEAR GROUP BY YEAR
)
SELECT YEAR,
       ROUND(SPENDING / 1e9, 2) AS SPENDING_BN,
       ROUND(CLAIMS / 1e6, 1) AS CLAIMS_M,
       ROUND(SPENDING / NULLIF(CLAIMS, 0), 2) AS SPEND_PER_CLAIM,
       DRUGS_REPORTED,
       ROUND(100 * (SPENDING / NULLIF(LAG(SPENDING) OVER (ORDER BY YEAR), 0) - 1), 1) AS YOY_GROWTH_PCT
FROM yearly ORDER BY YEAR;

-- @a2_top_drugs_2024
-- Highest spending drugs in 2024.
SELECT BRAND_NAME, GENERIC_NAME, DRUG_CLASS,
       ROUND(TOTAL_SPENDING / 1e9, 2) AS SPENDING_BN,
       ROUND(100 * TOTAL_SPENDING / NULLIF(SUM(TOTAL_SPENDING) OVER (), 0), 2) AS SHARE_PCT,
       ROUND(CLAIMS / 1e6, 2) AS CLAIMS_M,
       ROUND(TOTAL_SPENDING / NULLIF(CLAIMS, 0), 0) AS SPEND_PER_CLAIM
FROM MARTS.V_DRUG_YEAR
WHERE YEAR = 2024
QUALIFY ROW_NUMBER() OVER (ORDER BY TOTAL_SPENDING DESC) <= 15
ORDER BY TOTAL_SPENDING DESC;

-- @a3_class_trend
-- Spending and claims for selected cardiometabolic classes.
SELECT d.DRUG_CLASS, f.YEAR,
       ROUND(SUM(f.TOTAL_SPENDING) / 1e9, 2) AS SPENDING_BN,
       ROUND(SUM(f.CLAIMS) / 1e6, 2) AS CLAIMS_M
FROM MARTS.FCT_DRUG_YEAR f
JOIN MARTS.DIM_DRUG d USING (DRUG_ID)
WHERE d.DRUG_CLASS <> 'Other'
GROUP BY d.DRUG_CLASS, f.YEAR
ORDER BY d.DRUG_CLASS, f.YEAR;

-- @a4_price_volume
-- Expenditure growth decomposition, for drugs reported in both years.
-- “Price effect” represents spending per unit, not net transaction prices.
WITH p AS (
    SELECT DRUG_ID,
           MAX(IFF(YEAR = 2020, TOTAL_SPENDING, NULL)) AS S0,
           MAX(IFF(YEAR = 2024, TOTAL_SPENDING, NULL)) AS S1,
           MAX(IFF(YEAR = 2020, DOSAGE_UNITS, NULL)) AS U0,
           MAX(IFF(YEAR = 2024, DOSAGE_UNITS, NULL)) AS U1
    FROM MARTS.FCT_DRUG_YEAR
    WHERE YEAR IN (2020, 2024) GROUP BY DRUG_ID
)
SELECT 'Volume (more units dispensed)' AS COMPONENT,
       ROUND(SUM((U1 - U0) * (S0 / U0)) / 1e9, 2) AS CHANGE_BN
FROM p WHERE S0 IS NOT NULL AND S1 IS NOT NULL AND U0 > 0 AND U1 > 0
UNION ALL
SELECT 'Spending per unit effect',
       ROUND(SUM(((S1 / U1) - (S0 / U0)) * U1) / 1e9, 2)
FROM p WHERE S0 IS NOT NULL AND S1 IS NOT NULL AND U0 > 0 AND U1 > 0
UNION ALL
SELECT 'Not reported in 2020',
       ROUND(SUM(S1) / 1e9, 2)
FROM p WHERE S0 IS NULL AND S1 IS NOT NULL;

-- @a5_concentration_2024
-- Cumulative share of drug spend and claims by drug rank.
WITH ranked AS (
    SELECT TOTAL_SPENDING, CLAIMS,
           ROW_NUMBER() OVER (ORDER BY TOTAL_SPENDING DESC) AS RNK,
           COUNT(*) OVER () AS N
    FROM MARTS.FCT_DRUG_YEAR WHERE YEAR = 2024
)
SELECT RNK, N,
       SUM(TOTAL_SPENDING) OVER (
           ORDER BY RNK ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
       ) / NULLIF(SUM(TOTAL_SPENDING) OVER (), 0) AS CUM_SPEND_SHARE,
       SUM(CLAIMS) OVER (
           ORDER BY RNK ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
       ) / NULLIF(SUM(CLAIMS) OVER (), 0) AS CUM_CLAIM_SHARE
FROM ranked ORDER BY RNK;

-- @a6_brand_vs_generic_2024
-- Name-matching classification is an approximation, not FDA categorization.
SELECT d.BRAND_OR_GENERIC,
       COUNT(*) AS DRUGS,
       ROUND(100 * SUM(f.CLAIMS) / NULLIF(SUM(SUM(f.CLAIMS)) OVER (), 0), 1) AS CLAIMS_SHARE_PCT,
       ROUND(100 * SUM(f.TOTAL_SPENDING) / NULLIF(SUM(SUM(f.TOTAL_SPENDING)) OVER (), 0), 1) AS SPEND_SHARE_PCT,
       ROUND(SUM(f.TOTAL_SPENDING) / NULLIF(SUM(f.CLAIMS), 0), 0) AS SPEND_PER_CLAIM
FROM MARTS.FCT_DRUG_YEAR f JOIN MARTS.DIM_DRUG d USING (DRUG_ID)
WHERE f.YEAR = 2024 GROUP BY d.BRAND_OR_GENERIC;

-- @a7_fastest_growing
-- Biggest absolute expenditure increases from 2020 to 2024.
WITH p AS (
    SELECT DRUG_ID,
           MAX(IFF(YEAR = 2020, TOTAL_SPENDING, NULL)) AS S0,
           MAX(IFF(YEAR = 2024, TOTAL_SPENDING, NULL)) AS S1
    FROM MARTS.FCT_DRUG_YEAR GROUP BY DRUG_ID
)
SELECT d.BRAND_NAME, d.GENERIC_NAME, d.DRUG_CLASS,
       ROUND(S0 / 1e9, 2) AS SPEND_2020_BN,
       ROUND(S1 / 1e9, 2) AS SPEND_2024_BN,
       ROUND((S1 - S0) / 1e9, 2) AS INCREASE_BN,
       ROUND(S1 / NULLIF(S0, 0), 1) AS MULTIPLE
FROM p JOIN MARTS.DIM_DRUG d USING (DRUG_ID)
WHERE S0 > 0 AND S1 IS NOT NULL
ORDER BY S1 - S0 DESC LIMIT 10;

-- @a8_unit_price_inflation
-- Annualized change in spend/unit for drugs with >= $50M spending in 2024.
WITH p AS (
    SELECT DRUG_ID,
           MAX(IFF(YEAR = 2020, SPEND_PER_UNIT, NULL)) AS P0,
           MAX(IFF(YEAR = 2024, SPEND_PER_UNIT, NULL)) AS P1,
           MAX(IFF(YEAR = 2024, TOTAL_SPENDING, NULL)) AS S1
    FROM MARTS.FCT_DRUG_YEAR GROUP BY DRUG_ID
)
SELECT d.BRAND_OR_GENERIC, COUNT(*) AS DRUGS,
       ROUND(100 * MEDIAN(POWER(P1 / P0, 0.25) - 1), 1) AS MEDIAN_ANNUAL_PRICE_CHANGE_PCT,
       ROUND(100 * AVG(IFF(P1 > P0, 1, 0)), 1) AS PCT_DRUGS_PRICE_UP
FROM p JOIN MARTS.DIM_DRUG d USING (DRUG_ID)
WHERE P0 > 0 AND P1 > 0 AND S1 >= 5e7
GROUP BY d.BRAND_OR_GENERIC;

-- @a9_top_manufacturers_2024
SELECT MANUFACTURER,
       ROUND(TOTAL_SPENDING / 1e9, 2) AS SPENDING_BN, PRODUCTS
FROM MARTS.FCT_MANUFACTURER_YEAR
WHERE YEAR = 2024
ORDER BY TOTAL_SPENDING DESC LIMIT 10;
